/**
 * Code generator: turns a design document into the `XxxBase` class (fields, buildUi, event wiring,
 * empty virtual handlers) plus the one-off user class / main stubs.
 *
 * @author 张晓达
 */
public class DsGen {
    static String HEADER = "// <auto-generated>\n"
            + "// JNative Studio 设计器生成，请勿手工修改本文件：保存 .jnui 时会被覆盖。\n"
            + "// 在 {USER}.java 中重写事件处理方法即可。\n"
            + "// </auto-generated>\n";

    static String defaultHandler(DsNode n, DsEvent e, DsDoc d) {
        String owner = n.name;
        if (n == d.root) {
            owner = "form";
        }
        return "on" + DsUtil.capitalize(owner) + DsUtil.capitalize(e.name);
    }

    static String handlerParams(DsEvent e) {
        if (e.param.length() == 0) {
            return "";
        }
        return e.param + " e";
    }

    static String handlerSignature(String name, DsEvent e) {
        return "void " + name + "(" + handlerParams(e) + ")";
    }

    static void line(StringBuilder sb, int ind, String s) {
        int i = 0;
        while (i < ind) {
            sb.append("    ");
            i = i + 1;
        }
        sb.append(s);
        sb.append("\n");
    }

    static ArrayList<String> splitLines(String s) {
        ArrayList<String> out = new ArrayList<String>();
        if (s.length() == 0) {
            return out;
        }
        int start = 0;
        int i = 0;
        while (i <= s.length()) {
            if (i == s.length() || s.charAt(i) == '\n') {
                out.add(s.substring(start, i));
                start = i + 1;
            }
            i = i + 1;
        }
        return out;
    }

    static String itemsTsv(String items) {
        ArrayList<String> ls = splitLines(items);
        StringBuilder sb = new StringBuilder();
        int i = 0;
        while (i < ls.size()) {
            if (i > 0) {
                sb.append("\\t");
            }
            String t = DsUtil.javaString(ls.get(i));
            sb.append(t.substring(1, t.length() - 1));
            i = i + 1;
        }
        return sb.toString();
    }

    static String createExpr(DsNode n, DsType t) {
        if (t.name.equals("SegmentedControl")) {
            return "new SegmentedControl(\"" + itemsTsv(n.get("items")) + "\")";
        }
        if (t.name.equals("SplitPane")) {
            DsProp op = DsMeta.prop("SplitPane", "orientation");
            return "new SplitPane(" + op.codeOf(n.get("orientation")) + ")";
        }
        if (t.ctor.length() > 0) {
            DsProp cp = DsMeta.prop(t.name, t.ctor);
            return "new " + t.cls + "(" + DsMeta.formatValue(cp, n.get(t.ctor)) + ")";
        }
        return "new " + t.declType() + "()";
    }

    static String sizeExpr(int v, String var, String field) {
        if (v > 0) {
            return "" + v;
        }
        return var + "." + field;
    }

    static void emitNode(StringBuilder sb, DsNode n, int ind, DsDoc doc) {
        DsType t = DsMeta.find(n.type);
        String v = n.name;
        line(sb, ind, v + " = " + createExpr(n, t) + ";");
        // Properties (catalog order keeps output stable)
        ArrayList<DsProp> ps = DsMeta.propsFor(n.type);
        int i = 0;
        while (i < ps.size()) {
            DsProp p = ps.get(i);
            boolean deferred = n.type.equals("ComboBox") && p.name.equals("selectedIndex");
            if (n.has(p.name) && p.gen.length() > 0 && !deferred) {
                line(sb, ind, DsMeta.emit(p, v, n.get(p.name)));
            }
            i = i + 1;
        }
        // Items for list-like controls
        if (n.type.equals("ComboBox")) {
            ArrayList<String> items = splitLines(n.get("items"));
            int k = 0;
            while (k < items.size()) {
                line(sb, ind, v + ".addItem(" + DsUtil.javaString(items.get(k)) + ");");
                k = k + 1;
            }
            if (n.has("selectedIndex")) {
                line(sb, ind, DsMeta.emit(DsMeta.prop("ComboBox", "selectedIndex"), v, n.get("selectedIndex")));
            }
        }
        if (n.type.equals("ListView")) {
            ArrayList<String> items = splitLines(n.get("items"));
            line(sb, ind, "ArrayList<String> " + v + "Items = new ArrayList<String>();");
            int k = 0;
            while (k < items.size()) {
                line(sb, ind, v + "Items.add(" + DsUtil.javaString(items.get(k)) + ");");
                k = k + 1;
            }
            line(sb, ind, v + ".setItems(" + v + "Items);");
        }
        // Children
        int c = 0;
        while (c < n.children.size()) {
            DsNode ch = n.children.get(c);
            if (n.type.equals("Form")) {
                emitNode(sb, ch, ind, doc);
            } else {
                emitNode(sb, ch, ind, doc);
                emitAttach(sb, n, t, ch, c, ind);
            }
            c = c + 1;
        }
        // Events
        int e = 0;
        while (e < n.evNames.size()) {
            DsEvent ev = t.event(n.evNames.get(e));
            if (ev != null) {
                String h = n.evHandlers.get(e);
                String target = v;
                if (n.type.equals("Form")) {
                    target = "window";
                }
                if (ev.param.length() == 0) {
                    line(sb, ind, target + "." + ev.reg + "(() -> " + h + "());");
                } else {
                    line(sb, ind, target + "." + ev.reg + "(e -> " + h + "(e));");
                }
            }
            e = e + 1;
        }
    }

    /** Statements placing child `ch` of parent `p` (already created and configured). */
    static void emitAttach(StringBuilder sb, DsNode p, DsType pt, DsNode ch, int index, int ind) {
        String pv = p.name;
        String cv = ch.name;
        int w = ch.getInt("width");
        int h = ch.getInt("height");
        if (pt.container == DsType.ABSOLUTE) {
            line(sb, ind, pv + ".add(" + cv + ");");
            line(sb, ind, cv + ".setBounds(" + ch.getInt("x") + ", " + ch.getInt("y") + ", "
                    + sizeExpr(w, cv, "prefWidth") + ", " + sizeExpr(h, cv, "prefHeight") + ");");
            return;
        }
        if (pt.container == DsType.GRID) {
            line(sb, ind, pv + ".addAtSpan(" + cv + ", " + ch.getInt("col") + ", " + ch.getInt("row") + ", "
                    + ch.getInt("colSpan") + ", " + ch.getInt("rowSpan") + ");");
            return;
        }
        if (pt.container == DsType.TABS) {
            line(sb, ind, pv + ".addTab(" + DsUtil.javaString(ch.get("tabTitle")) + ", " + cv + ");");
            return;
        }
        if (w > 0 || h > 0) {
            line(sb, ind, cv + ".setPrefSize(" + sizeExpr(w, cv, "prefWidth") + ", " + sizeExpr(h, cv, "prefHeight") + ");");
        }
        if (pt.container == DsType.SINGLE) {
            line(sb, ind, pv + ".setContent(" + cv + ");");
        } else if (pt.container == DsType.SPLIT) {
            if (index == 0) {
                line(sb, ind, pv + ".setFirst(" + cv + ");");
            } else {
                line(sb, ind, pv + ".setSecond(" + cv + ");");
            }
        } else {
            line(sb, ind, pv + ".add(" + cv + ");");
        }
    }

    static void collectHandlers(DsDoc doc, ArrayList<String> names, ArrayList<DsEvent> evs) {
        ArrayList<DsNode> all = doc.allNodes();
        int i = 0;
        while (i < all.size()) {
            DsNode n = all.get(i);
            DsType t = DsMeta.find(n.type);
            int e = 0;
            while (e < n.evNames.size()) {
                DsEvent ev = t.event(n.evNames.get(e));
                String h = n.evHandlers.get(e);
                if (ev != null && names.indexOf(h) < 0) {
                    names.add(h);
                    evs.add(ev);
                }
                e = e + 1;
            }
            i = i + 1;
        }
    }

    /** Generated `{Class}Base.java` source. */
    static String generateBase(DsDoc doc) {
        StringBuilder sb = new StringBuilder();
        sb.append(replaceAll(HEADER, "{USER}", doc.className));
        sb.append("import jnative.ui.*;\n");
        sb.append("import jnative.graphics.*;\n\n");
        line(sb, 0, "public class " + doc.className + "Base {");
        line(sb, 1, "Window window;");
        ArrayList<DsNode> all = doc.allNodes();
        int i = 1;
        while (i < all.size()) {
            DsNode n = all.get(i);
            DsType t = DsMeta.find(n.type);
            line(sb, 1, t.declType() + " " + n.name + ";");
            i = i + 1;
        }
        sb.append("\n");
        line(sb, 1, "void buildUi() {");
        DsNode form = doc.root;
        line(sb, 2, "window = new Window(" + DsUtil.javaString(form.get("title")) + ", " + form.getInt("width") + ", "
                + form.getInt("height") + ");");
        int c = 0;
        while (c < form.children.size()) {
            DsNode content = form.children.get(c);
            emitNode(sb, content, 2, doc);
            line(sb, 2, "window.setContent(" + content.name + ");");
            c = c + 1;
        }
        // form-level events
        int e = 0;
        DsType ft = DsMeta.find("Form");
        while (e < form.evNames.size()) {
            DsEvent ev = ft.event(form.evNames.get(e));
            if (ev != null) {
                line(sb, 2, "window." + ev.reg + "(() -> " + form.evHandlers.get(e) + "());");
            }
            e = e + 1;
        }
        line(sb, 1, "}");
        sb.append("\n");
        line(sb, 1, "void show() {");
        line(sb, 2, "if (window == null) {");
        line(sb, 3, "buildUi();");
        line(sb, 2, "}");
        line(sb, 2, "window.show();");
        line(sb, 1, "}");

        ArrayList<String> names = new ArrayList<String>();
        ArrayList<DsEvent> evs = new ArrayList<DsEvent>();
        collectHandlers(doc, names, evs);
        int h = 0;
        while (h < names.size()) {
            sb.append("\n");
            line(sb, 1, "/** 事件处理：在 " + doc.className + " 中重写。 */");
            line(sb, 1, handlerSignature(names.get(h), evs.get(h)) + " {");
            line(sb, 1, "}");
            h = h + 1;
        }
        line(sb, 0, "}");
        return sb.toString();
    }

    static String replaceAll(String s, String from, String to) {
        StringBuilder sb = new StringBuilder();
        int i = 0;
        while (i < s.length()) {
            if (DsUtil.startsAt(s, from, i)) {
                sb.append(to);
                i = i + from.length();
            } else {
                sb.append(s.charAt(i));
                i = i + 1;
            }
        }
        return sb.toString();
    }

    /** User-owned class created once next to the base. */
    static String userStub(DsDoc doc) {
        StringBuilder sb = new StringBuilder();
        sb.append("import jnative.ui.*;\n");
        sb.append("import jnative.graphics.*;\n\n");
        line(sb, 0, "/** " + doc.className + " 的业务逻辑。界面由 " + doc.className + ".jnui 设计器生成到 " + doc.className + "Base。 */");
        line(sb, 0, "public class " + doc.className + " extends " + doc.className + "Base {");
        line(sb, 1, doc.className + "() {");
        line(sb, 2, "buildUi();");
        line(sb, 1, "}");
        line(sb, 0, "}");
        return sb.toString();
    }

    static String mainStub(DsDoc doc) {
        StringBuilder sb = new StringBuilder();
        sb.append("import jnative.ui.*;\n\n");
        line(sb, 0, "public class Main {");
        line(sb, 1, "public static void main(String[] args) {");
        line(sb, 2, "Application app = new Application();");
        line(sb, 2, doc.className + " form = new " + doc.className + "();");
        line(sb, 2, "form.show();");
        line(sb, 2, "app.run();");
        line(sb, 1, "}");
        line(sb, 0, "}");
        return sb.toString();
    }

    /** Method text appended to the user class when an event is bound. */
    static String handlerStub(String handler, DsEvent e) {
        StringBuilder sb = new StringBuilder();
        line(sb, 1, "@Override");
        line(sb, 1, handlerSignature(handler, e) + " {");
        line(sb, 2, "// TODO: 处理" + e.label + "事件");
        line(sb, 1, "}");
        return sb.toString();
    }

    /** True when `src` already declares a method called `name`. */
    static boolean hasMethod(String src, String name) {
        return src.indexOf("void " + name + "(") >= 0;
    }

    /** Insert `stub` before the final closing brace of the class in `src`. */
    static String insertMethod(String src, String stub) {
        int end = src.lastIndexOf("}");
        if (end < 0) {
            return src + "\n" + stub;
        }
        String head = src.substring(0, end);
        while (head.length() > 0 && (head.endsWith("\n") || head.endsWith(" "))) {
            head = head.substring(0, head.length() - 1);
        }
        return head + "\n\n" + stub + "}\n";
    }

    /** 1-based line number of `void name(` in src, or 1. */
    static int lineOfMethod(String src, String name) {
        int at = src.indexOf("void " + name + "(");
        if (at < 0) {
            return 1;
        }
        int line = 1;
        int i = 0;
        while (i < at) {
            if (src.charAt(i) == '\n') {
                line = line + 1;
            }
            i = i + 1;
        }
        return line;
    }
}
