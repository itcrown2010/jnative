package io.jnative.pkg;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/** Exact resolved graph on disk — jnative.lock (stable ordering, human-diffable).
 * @author 张晓达
 */
public final class Lockfile {
    public static final String FORMAT_VERSION = "1";

    private String resolverVersion = DependencyResolver.RESOLVER_VERSION;
    private String manifestFingerprint = "";
    private final Map<String, LockEntry> entries = new TreeMap<>();

    public record LockEntry(
            String id,
            String version,
            String source,
            String contentHash,
            List<String> dependencies,
            List<String> features,
            String targetVariant,
            String packageType
    ) {
    }

    public String resolverVersion() {
        return resolverVersion;
    }

    public void setResolverVersion(String resolverVersion) {
        this.resolverVersion = resolverVersion;
    }

    public String manifestFingerprint() {
        return manifestFingerprint;
    }

    public void setManifestFingerprint(String manifestFingerprint) {
        this.manifestFingerprint = manifestFingerprint == null ? "" : manifestFingerprint;
    }

    public Map<String, LockEntry> entries() {
        return entries;
    }

    public static Lockfile fromGraph(ResolvedDependencyGraph graph, String manifestFp) {
        Lockfile lock = new Lockfile();
        lock.setManifestFingerprint(manifestFp);
        for (ResolvedPackage p : graph.packages().values()) {
            List<String> deps = new ArrayList<>();
            for (PackageId d : p.dependencies()) {
                deps.add(d.coordinate());
            }
            deps.sort(String::compareTo);
            List<String> feats = new ArrayList<>(p.features());
            feats.sort(String::compareTo);
            lock.entries.put(p.id().coordinate(), new LockEntry(
                    p.id().coordinate(),
                    p.version().toString(),
                    p.source(),
                    p.contentHash(),
                    deps,
                    feats,
                    "",
                    p.packageType()
            ));
        }
        return lock;
    }

    public ResolvedDependencyGraph toGraph(PackageId root) {
        ResolvedDependencyGraph g = new ResolvedDependencyGraph(root);
        Map<PackageId, ResolvedPackage> tmp = new LinkedHashMap<>();
        for (LockEntry e : entries.values()) {
            PackageId id = PackageId.parse(e.id());
            ResolvedPackage rp = new ResolvedPackage(
                    id,
                    SemanticVersion.parse(e.version()),
                    e.source(),
                    e.contentHash(),
                    new java.util.LinkedHashSet<>(e.features()),
                    false,
                    java.util.Set.of(),
                    e.packageType(),
                    ""
            );
            tmp.put(id, rp);
        }
        for (LockEntry e : entries.values()) {
            ResolvedPackage rp = tmp.get(PackageId.parse(e.id()));
            for (String d : e.dependencies()) {
                rp.dependencies().add(PackageId.parse(d));
            }
            g.put(rp);
        }
        return g;
    }

    public void save(Path file) throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("# This file is automatically @generated by JNative.\n");
        sb.append("# It is not intended for manual editing.\n");
        sb.append("version = \"").append(FORMAT_VERSION).append("\"\n");
        sb.append("resolver = \"").append(resolverVersion).append("\"\n");
        sb.append("manifest = \"").append(manifestFingerprint).append("\"\n\n");
        for (LockEntry e : entries.values()) {
            sb.append("[[package]]\n");
            sb.append("name = \"").append(e.id()).append("\"\n");
            sb.append("version = \"").append(e.version()).append("\"\n");
            sb.append("source = \"").append(escape(e.source())).append("\"\n");
            sb.append("hash = \"sha256:").append(e.contentHash()).append("\"\n");
            sb.append("type = \"").append(e.packageType()).append("\"\n");
            if (!e.dependencies().isEmpty()) {
                sb.append("dependencies = [");
                for (int i = 0; i < e.dependencies().size(); i++) {
                    if (i > 0) {
                        sb.append(", ");
                    }
                    sb.append('"').append(e.dependencies().get(i)).append('"');
                }
                sb.append("]\n");
            }
            if (!e.features().isEmpty()) {
                sb.append("features = [");
                for (int i = 0; i < e.features().size(); i++) {
                    if (i > 0) {
                        sb.append(", ");
                    }
                    sb.append('"').append(e.features().get(i)).append('"');
                }
                sb.append("]\n");
            }
            sb.append('\n');
        }
        Path tmp = file.resolveSibling(file.getFileName() + ".tmp");
        Files.writeString(tmp, sb.toString(), StandardCharsets.UTF_8);
        Files.move(tmp, file, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
    }

    public static Lockfile load(Path file) throws IOException {
        Lockfile lock = new Lockfile();
        if (!Files.isRegularFile(file)) {
            return lock;
        }
        String text = Files.readString(file, StandardCharsets.UTF_8);
        MatcherField mf = new MatcherField(text);
        lock.resolverVersion = mf.top("resolver", DependencyResolver.RESOLVER_VERSION);
        lock.manifestFingerprint = mf.top("manifest", "");
        for (String block : mf.packages()) {
            String name = field(block, "name");
            String version = field(block, "version");
            String source = field(block, "source");
            String hash = field(block, "hash");
            if (hash.startsWith("sha256:")) {
                hash = hash.substring(7);
            }
            String type = field(block, "type");
            if (type.isEmpty()) {
                type = "source";
            }
            List<String> deps = arrayField(block, "dependencies");
            List<String> feats = arrayField(block, "features");
            lock.entries.put(name, new LockEntry(name, version, source, hash, deps, feats, "", type));
        }
        return lock;
    }

    private static String field(String block, String key) {
        java.util.regex.Matcher m = java.util.regex.Pattern
                .compile("^" + key + "\\s*=\\s*\"([^\"]*)\"", java.util.regex.Pattern.MULTILINE)
                .matcher(block);
        return m.find() ? m.group(1) : "";
    }

    private static List<String> arrayField(String block, String key) {
        java.util.regex.Matcher m = java.util.regex.Pattern
                .compile(key + "\\s*=\\s*\\[([^\\]]*)]")
                .matcher(block);
        List<String> out = new ArrayList<>();
        if (!m.find()) {
            return out;
        }
        java.util.regex.Matcher s = java.util.regex.Pattern.compile("\"([^\"]+)\"").matcher(m.group(1));
        while (s.find()) {
            out.add(s.group(1));
        }
        return out;
    }

    private static String escape(String s) {
        return s == null ? "" : s.replace("\\", "\\\\").replace("\"", "\\\"");
    }

    private static final class MatcherField {
        private final String text;

        MatcherField(String text) {
            this.text = text;
        }

        String top(String key, String def) {
            java.util.regex.Matcher m = java.util.regex.Pattern
                    .compile("^" + key + "\\s*=\\s*\"([^\"]*)\"", java.util.regex.Pattern.MULTILINE)
                    .matcher(text);
            return m.find() ? m.group(1) : def;
        }

        List<String> packages() {
            String[] parts = text.split("\\[\\[package]]");
            List<String> out = new ArrayList<>();
            for (int i = 1; i < parts.length; i++) {
                out.add(parts[i]);
            }
            return out;
        }
    }
}
